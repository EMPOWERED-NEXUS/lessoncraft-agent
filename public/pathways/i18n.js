export function t(lang, key, vars = {}) {
  const pack = STRINGS[lang] || STRINGS.en;
  const template = pack[key] || STRINGS.en[key] || key;
  return template.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? ""));
}

export function getLang(storage) {
  const value = storage.getItem(LANG_KEY);
  return value === "fr" ? "fr" : "en";
}

export function setLang(storage, lang) {
  storage.setItem(LANG_KEY, lang === "fr" ? "fr" : "en");
}

export function applyLanguage(root, lang) {
  const pack = STRINGS[lang] || STRINGS.en;
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = pack[node.dataset.i18n];
    if (!value) return;
    const text = [...node.childNodes].find((child) => child.nodeType === 3 && child.textContent.trim());
    if (text && node.children.length) text.textContent = `${value} `;
    else if (!node.children.length) node.textContent = value;
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const value = pack[node.dataset.i18nPlaceholder];
    if (value) node.setAttribute("placeholder", value);
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    const value = pack[node.dataset.i18nAria];
    if (value) node.setAttribute("aria-label", value);
  });
  root.documentElement.lang = lang === "fr" ? "fr" : "en";
}
